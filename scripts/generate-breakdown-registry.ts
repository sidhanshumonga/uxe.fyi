// Writes src/generated/breakdown-demos.ts: a static import for every
// content/breakdowns/<slug>/Demo.tsx, so pages can render demos by slug.
// Bundlers need static imports, so this list can't be built at runtime.
//
// Runs automatically on npm install, dev, build and content:check.
// Added a breakdown while `npm run dev` is running? Restart dev.

import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const dir = path.join(root, 'content', 'breakdowns');
const out = path.join(root, 'src', 'generated', 'breakdown-demos.ts');

const slugs = fs.existsSync(dir)
  ? fs.readdirSync(dir, { withFileTypes: true })
      .filter((d) => d.isDirectory() && !d.name.startsWith('_') && !d.name.startsWith('.'))
      .filter((d) => fs.existsSync(path.join(dir, d.name, 'Demo.tsx')))
      .map((d) => d.name)
      .sort()
  : [];

const lines = [
  '// AUTO-GENERATED by scripts/generate-breakdown-registry.ts — do not edit.',
  "import type { ComponentType } from 'react';",
  ...slugs.map((s, i) => `import Demo${i} from '../../content/breakdowns/${s}/Demo';`),
  '',
  'export const BREAKDOWN_DEMOS: Record<string, ComponentType> = {',
  ...slugs.map((s, i) => `  '${s}': Demo${i},`),
  '};',
  '',
];

fs.mkdirSync(path.dirname(out), { recursive: true });
const next = lines.join('\n');
if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== next) fs.writeFileSync(out, next);
console.log(`✓ breakdown registry: ${slugs.length} demo${slugs.length === 1 ? '' : 's'}`);
